/** ห่อข้อความผู้ใช้ให้ชัดว่าเป็นข้อมูล ไม่ใช่คำสั่ง (ลบแท็กปลอมที่ผู้ใช้อาจพิมพ์มา) */
export function wrapUntrusted(tag: string, content: string): string {
  const cleaned = content.replace(new RegExp(`</?${tag}[^>]*>`, "gi"), "");
  return `<${tag}>\n${cleaned}\n</${tag}>`;
}
