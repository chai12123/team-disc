/**
 * ลำดับการแสดงผล: สลับแกนให้กระจาย (D1, Di1, I1, ... , D2, Di2, ...)
 * เพื่อไม่ให้ผู้ตอบเห็นข้อของแกนเดียวกันติดกัน
 */
export const ITEM_ORDER: string[] = (() => {
  const byScale = new Map<string, AssessmentItem[]>();
  for (const it of ITEM_BANK) {
    const arr = byScale.get(it.scale) ?? [];
    arr.push(it);
    byScale.set(it.scale, arr);
  }
  const scales = Array.from(byScale.keys());
  const order: string[] = [];
  for (let i = 0; i < 8; i++) {
    for (const s of scales) {
      const it = byScale.get(s)![i];
      if (it) order.push(it.id);
    }
  }
  return order;
})();

