export interface AssessmentItem {
  id: string;
  scale: AxisKey;
  text: string;
  reverseScored: boolean;
  context: string;
  rationale: string;
  pairGroup: string | null;
  version: number;
}

const V = 1;

type Row = [
  id: string,
  text: string,
  reverse: boolean,
  context: string,
  rationale: string,
  pair: string | null,
];

function rows(scale: AxisKey, list: Row[]): AssessmentItem[] {
  return list.map(([id, text, reverseScored, context, rationale, pairGroup]) => ({
    id,
    scale,
    text,
    reverseScored,
    context,
    rationale,
    pairGroup,
    version: V,
  }));
}

